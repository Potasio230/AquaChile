-- 2. CREACION DE TABLAS

CREATE TABLE usuario (
    id_usuario      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR2(100) NOT NULL,
    email           VARCHAR2(120) UNIQUE NOT NULL,
    rol             VARCHAR2(30) DEFAULT 'PSICOLOGO' NOT NULL,
    activo          CHAR(1) DEFAULT 'S' CHECK (activo IN ('S', 'N'))
);

CREATE TABLE candidato (
    id_candidato    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut             VARCHAR2(12) UNIQUE NOT NULL,
    nombre_completo VARCHAR2(120) NOT NULL,
    email           VARCHAR2(120) NOT NULL,
    telefono        VARCHAR2(20),
    fecha_registro  DATE DEFAULT SYSDATE
);

CREATE TABLE familia_cargo (
    id_familia      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR2(80) NOT NULL,
    descripcion     VARCHAR2(255)
);

CREATE TABLE cargo (
    id_cargo        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_familia      NUMBER NOT NULL,
    nombre          VARCHAR2(100) NOT NULL,
    requisitos      VARCHAR2(500),
    CONSTRAINT fk_cargo_familia FOREIGN KEY (id_familia) REFERENCES familia_cargo(id_familia)
);

CREATE TABLE solicitud_evaluacion (
    id_solicitud    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidato    NUMBER NOT NULL,
    id_cargo        NUMBER NOT NULL,
    fecha_solicitud DATE DEFAULT SYSDATE,
    CONSTRAINT fk_sol_candidato FOREIGN KEY (id_candidato) REFERENCES candidato(id_candidato),
    CONSTRAINT fk_sol_cargo FOREIGN KEY (id_cargo) REFERENCES cargo(id_cargo)
);

CREATE TABLE evaluacion (
    id_evaluacion   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud    NUMBER NOT NULL,
    id_psicologo    NUMBER,
    estado          VARCHAR2(30) DEFAULT 'ASIGNADO' NOT NULL,
    fecha_creacion  DATE DEFAULT SYSDATE,
    fecha_actualizacion DATE DEFAULT SYSDATE,
    CONSTRAINT fk_eval_solicitud FOREIGN KEY (id_solicitud) REFERENCES solicitud_evaluacion(id_solicitud),
    CONSTRAINT fk_eval_psicologo FOREIGN KEY (id_psicologo) REFERENCES usuario(id_usuario),
    CONSTRAINT chk_eval_estado CHECK (estado IN ('ASIGNADO', 'ENTREVISTADO', 'GENERANDO_INFORME', 'EN_REVISION', 'ENVIADO', 'CANCELADO'))
);

CREATE TABLE log_auditoria_evaluacion (
    id_log              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evaluacion       NUMBER NOT NULL,
    accion              VARCHAR2(20) NOT NULL,
    estado_anterior     VARCHAR2(30),
    estado_nuevo        VARCHAR2(30),
    usuario_responsable VARCHAR2(100) NOT NULL,
    fecha_evento        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    detalle             VARCHAR2(255)
);

